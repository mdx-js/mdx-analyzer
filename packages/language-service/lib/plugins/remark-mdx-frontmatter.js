/**
 * @import {Yaml} from 'mdast'
 * @import {VirtualCodePlugin} from './plugin.js'
 */

import {buildFrontmatterValidation} from './frontmatter-schema.js'

/**
 * @param {unknown} options
 * @returns {VirtualCodePlugin}
 */
export function remarkMdxFrontmatter(options) {
  const opts = typeof options === 'object' && options !== null ? options : {}
  const name = 'name' in opts ? String(opts.name) : 'frontmatter'
  const type = 'type' in opts ? String(opts.type) : undefined

  return () => {
    let hasFrontmatter = false
    /** @type {Yaml | undefined} */
    let yamlNode

    return {
      visit(node) {
        if (node.type === 'toml' || node.type === 'yaml') {
          hasFrontmatter = true
        }

        if (node.type === 'yaml') {
          yamlNode = node
        }
      },

      finalize(mdx) {
        // If a type is configured, the export is always that type. Otherwise
        // preserve the historic behavior: `any` when frontmatter is present,
        // `undefined` when it’s absent.
        const annotation = type || (hasFrontmatter ? 'any' : 'undefined')
        const header =
          '/** Generated by [remark-mdx-frontmatter](https://github.com/remcohaszing/remark-mdx-frontmatter) */\nexport const ' +
          name +
          ' = /** @type {' +
          annotation +
          '} */ (undefined)'

        // Value checking only makes sense with a concrete type and YAML content
        // to check against it.
        if (!type || !yamlNode) {
          return header
        }

        const start = yamlNode.position?.start?.offset
        const end = yamlNode.position?.end?.offset
        if (start === undefined || end === undefined) {
          return header
        }

        // The YAML node’s position spans the whole `---` fenced block; find
        // where its value starts within it.
        const valueOffset =
          start + mdx.slice(start, end).indexOf(yamlNode.value)
        const validation = buildFrontmatterValidation(
          yamlNode.value,
          valueOffset,
          type
        )
        if (!validation) {
          return header
        }

        const value = header + '\n' + validation.text
        const padding = header.length + 1
        return {
          value,
          mappings: [
            {
              ...validation.mapping,
              generatedOffsets: validation.mapping.generatedOffsets.map(
                (offset) => offset + padding
              )
            }
          ]
        }
      }
    }
  }
}
